"""Arma D:/rust/mamba_instalar (lo que se copia a AddOns) y el manifiesto de los generados (18-11).

Uso: python -I tools/asistente/armar_instalar.py [--dest CARPETA] [--manifiesto JSON] [--desde AAAA-MM-DDTHH:MM]
     (la tarea Mamba_Actualizar pasa su propia carpeta y la hora en que empezó su construcción)
     python -I tools/asistente/control_zip.py D:\\rust\\mamba_instalar --manifiesto D:\\rust\\noche\\manifiesto_mamba.json --estricto

ALCANCE (Cristian, 18-11: "necesitamos al menos todas las razas horda… todas las clases horda"):
interruptores: True = va en el armado; False = se apaga (el código queda en el repositorio).
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import shutil
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[2]
ADDON = RAIZ / "addon"
DEST = Path(r"D:\rust\mamba_instalar")
MANIFIESTO = Path(r"D:\rust\noche\manifiesto_mamba.json")
DESDE = dt.datetime(2026, 11, 18, 2, 59).timestamp()  # generados de esta construcción

ALCANCE = {
    # Guías de la Alianza
    "Polestar_Guides_Alliance": False, "Polestar_Guides_Human": False, "Polestar_Guides_Dwarf": False,
    "Polestar_Guides_Gnome": False, "Polestar_Guides_NightElf": False,
    # Idiomas: quedan esMX y esES
    "Polestar_deDE": False, "Polestar_frFR": False, "Polestar_koKR": False, "Polestar_ptBR": False,
    "Polestar_ruRU": False, "Polestar_zhCN": False, "Polestar_zhTW": False,
    # Siempre fuera: herramientas de desarrollo y lo que no se reconstruye (QuestieDB/Leffe)
    "Polestar_Recorder": False, "Polestar_Skin_Example": False,
    "Polestar_Experimental": False, "Polestar_Nav_EK": False, "Polestar_Nav_Kalimdor": False,
}

# Generados que esta construcción NO rehace y se aceptan, revisada su cabecera (solo fuentes autorizadas).
ACEPTADOS = {
    "Asistente_Datos/": "generador propio WOW_FOREVER (build 1.60.1.70532)",
    "Asistente_Servicios/": "generador propio WOW_FOREVER desde forever-db",
    "ForeverCore/Data/Credits.lua": "créditos desde THIRD_PARTY.md",
    "Polestar/Core/Credits.lua": "créditos de Polestar",
    "Polestar/Core/LegacySteps.lua": "pasos de versiones anteriores de las guías (claves de guardado)",
    "Polestar/Gear/SpecData.lua": "pesos de Polestar, wowsims MIT, ForeverLevelingBiS MIT (aceptadas 18-11)",
    "Polestar/QoL/ClassSpells.lua": "ForeverTDB (autorizada 17-11)",
    "Polestar/QoL/Data.lua": "pfQuest MIT + marcos de mapa del cliente",
    "Polestar/Quests/QuestDB.lua": "código de consulta (no datos)",
    "Polestar/Talents/Builds.lua": "talents/forever + tablas del cliente (wago)",
    "Polestar/UI/ZoneArtOverlays.lua": "tablas de mapa del cliente",
    "Polestar_Arcade/data/": "Freedoom (licencia tipo BSD, aceptada 18-11)",
    "Polestar_ItemDB/": "tablas del cliente (wago) + ForeverLevelingBiS MIT",
    "Polestar_Looks/GameArt.lua": "tablas de atlas del cliente",
    "SkillUpForever/Data/": "wago + CMaNGOS classic-db GPL-3.0",
    "/Subzones.lua": "WMOAreaTable/AreaTable del cliente (wago)",
}
GEN = re.compile(rb"Generated by|Generado por", re.I)


def main() -> int:
    global DEST, MANIFIESTO, DESDE
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", type=Path, default=DEST)
    ap.add_argument("--manifiesto", type=Path, default=MANIFIESTO)
    ap.add_argument("--desde", help="generados más nuevos que esta hora = de esta construcción (ISO)")
    a = ap.parse_args()
    DEST, MANIFIESTO = a.dest, a.manifiesto
    if a.desde:
        DESDE = dt.datetime.fromisoformat(a.desde).timestamp()
    MANIFIESTO.parent.mkdir(parents=True, exist_ok=True)
    if DEST.exists():
        shutil.rmtree(DEST)
    DEST.mkdir(parents=True)
    carpetas = sorted(d.name for d in ADDON.iterdir()
                      if d.is_dir() and any(d.glob("*.toc")) and ALCANCE.get(d.name, True))
    for c in carpetas:
        ign = (shutil.ignore_patterns("tools", "curseforge", "FreedoomArcade.toc") if c == "Polestar_Arcade"
               else shutil.ignore_patterns(".git*"))
        shutil.copytree(ADDON / c, DEST / c, ignore=ign)
    (DEST / "Polestar_Arcade" / "src" / "FreedoomArcade.toc").unlink(missing_ok=True)
    man, viejos, aceptados = {}, [], []
    for p in sorted(DEST.rglob("*")):
        if not p.is_file() or p.suffix.lower() not in (".lua", ".json", ".xml", ".txt"):
            continue
        if not GEN.search(p.read_bytes()[:4096]):
            continue
        rel = p.relative_to(DEST).as_posix()
        motivo = next((m for k, m in ACEPTADOS.items() if rel.startswith(k) or (k.startswith("/") and rel.endswith(k))), None)
        if (ADDON / rel).stat().st_mtime >= DESDE:
            man[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
        elif motivo:
            man[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
            aceptados.append(f"{rel}: {motivo}")
        else:
            viejos.append(rel)
    MANIFIESTO.write_text(json.dumps({"archivos": man}, indent=1), "utf-8")
    MANIFIESTO.with_name("manifiesto_mamba_aceptados.txt").write_text("\n".join(aceptados) + "\n", "utf-8")
    apagadas = sorted(k for k, v in ALCANCE.items() if not v and (ADDON / k).is_dir())
    print(f"{len(carpetas)} carpetas en el armado; apagadas: {' '.join(apagadas)}")
    print(f"manifiesto: {len(man)} ({len(aceptados)} aceptados viejos); generados viejos sin aceptar: {len(viejos)}")
    for v in viejos:
        print("  viejo:", v)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
