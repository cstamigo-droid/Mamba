"""Control de licencias antes de repartir un zip de Mamba (ARQUITECTURA §13f.1).

Uso:
    python -I tools/asistente/control_zip.py <carpeta-o-zip> [--manifiesto construccion.json]

Revisa cada archivo que va en el zip y lo RECHAZA (sale con 1) si:
  1. su cabecera dice que se generó con los mapas privados de Leffe
     ("--leffe", "leffe <hash>", "Leffe's navigation maps");
  2. su cabecera "Generated by" nombra QuestieDB, DingDB o forever-vo como fuente;
  3. un LICENSE-DATA.txt o CREDITS.md empacado nombra esas fuentes como
     origen de lo que lleva la carpeta;
  4. es un archivo generado ("Generated by ... Do not edit") que no está en el
     manifiesto de nuestra construcción, o su sha256 no coincide.

El código que solo MENCIONA a Questie o Leffe (por ejemplo, para leer Questie si
el jugador lo tiene instalado) no se rechaza: se mira solo la cabecera de los
archivos generados y los avisos de datos.

Sin --manifiesto, la regla 4 se informa como aviso y no rechaza (sirve para
medir, no para repartir). Para repartir, el manifiesto es obligatorio: --estricto.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

# Regla 1. Ojo: "SpellEffect" contiene "lEffe"; por eso no se busca "leffe" suelto.
LEFFE = re.compile(r"--leffe\b|\bleffe [0-9a-f]{8,}\b|Leffe's navigation maps|store-leffe", re.I)
# Reglas 2 y 3: fuentes con permiso solo para Polestar o sin licencia.
AJENAS = re.compile(r"\bQuestie(?:DB)?\b|\bDingDB\b|\bforever-vo\b|\bLeffe\b", re.I)
GENERADO = re.compile(r"^--\s*(Generated by|Generado por)\b", re.I)
AVISOS = {"license-data.txt", "credits.md"}
CABECERA = 4096  # bytes que se leen de cada archivo para la cabecera


def _archivos(origen: Path):
    """(ruta relativa, bytes) de cada archivo de una carpeta o un zip."""
    if origen.is_file() and origen.suffix.lower() == ".zip":
        with zipfile.ZipFile(origen) as z:
            for info in z.infolist():
                if not info.is_dir():
                    yield info.filename.replace("\\", "/"), z.read(info)
    else:
        for p in sorted(origen.rglob("*")):
            if p.is_file():
                yield p.relative_to(origen).as_posix(), p.read_bytes()


def _cabecera(datos: bytes) -> str:
    texto = datos[:CABECERA].decode("utf-8", "replace")
    lineas = []
    for linea in texto.splitlines():
        if linea.startswith("--") or not linea.strip():
            lineas.append(linea)
        else:
            break
    return "\n".join(lineas)


FOREVER_DB = re.compile(r"\bforever-db\b", re.I)


def _secciones_fuente(texto: str):
    """Párrafos de un LICENSE-DATA/CREDITS (separados por una línea vacía) que nombran una fuente
    ajena, en todo su texto (no solo el título). -> primera línea del párrafo.

    Excepción, una sola y a propósito: un párrafo que habla de **forever-db**. forever-db es el
    conjunto de datos que Polestar publica como GPL-3.0-only, y su NOTICE.md dice que "every value in
    its tables is held by at least one of the independent sources below"; nombra a QuestieDB entre sus
    créditos, no como única fuente. Las guías y los nombres de Polestar, en cambio, dicen que llevan
    hechos de QuestieDB "with the Questie maintainers' agreement" (THIRD_PARTY.md): esos sí se rechazan.
    """
    for parrafo in re.split(r"\n\s*\n", texto.replace("\r\n", "\n")):
        if AJENAS.search(parrafo) and not FOREVER_DB.search(parrafo):
            primera = next((l.strip() for l in parrafo.splitlines() if l.strip()), "")
            yield primera + " … " + AJENAS.search(parrafo).group(0)


def revisar(origen: Path, manifiesto: dict | None) -> tuple[list[str], list[str]]:
    rechazos, avisos = [], []
    for ruta, datos in _archivos(origen):
        nombre = ruta.rsplit("/", 1)[-1].lower()
        if nombre in AVISOS:
            texto = datos.decode("utf-8", "replace")
            for titulo in _secciones_fuente(texto):
                if AJENAS.search(titulo):
                    rechazos.append(f"{ruta}: nombra una fuente ajena como origen: «{titulo[:90]}»")
            continue
        if not ruta.lower().endswith((".lua", ".json", ".xml", ".txt")):
            continue
        cab = _cabecera(datos)
        gen = [l for l in cab.splitlines() if GENERADO.match(l)]
        # Regla 1, solo en generados: el código (Nav/Baked.lua) explica a Leffe en comentarios.
        # La marca de datos "leffe <hash>" puede ir en la primera línea de datos (Legs.lua).
        if gen and (LEFFE.search(cab) or LEFFE.search(datos[:65536].decode("utf-8", "replace"))):
            rechazos.append(f"{ruta}: generado con los mapas de Leffe")
        if gen:
            # Solo las líneas que declaran fuentes: un comentario como "Neither QuestieDB nor
            # AtlasLoot holds these" (SkillUpForever/Data/Sources.lua) no es una fuente.
            fuentes = "\n".join(l for l in cab.splitlines()
                                if GENERADO.match(l) or re.match(r"^--\s*(Sources?|From|Fuentes?)\b", l, re.I))
            if AJENAS.search(fuentes):
                rechazos.append(f"{ruta}: generado con una fuente ajena: «{gen[0][:120]}»")
            huella = hashlib.sha256(datos).hexdigest()
            if manifiesto is None:
                avisos.append(f"{ruta}: generado; sin manifiesto no se puede comprobar que es nuestro")
            elif manifiesto.get(ruta) != huella:
                rechazos.append(f"{ruta}: generado que no es de nuestra construcción (falta en el manifiesto o cambió)")
    return rechazos, avisos


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 2
    origen = Path(argv[0])
    manifiesto = None
    if "--manifiesto" in argv:
        manifiesto = json.loads(Path(argv[argv.index("--manifiesto") + 1]).read_text("utf-8"))
        manifiesto = manifiesto.get("archivos", manifiesto)
    elif "--estricto" in argv:
        print("RECHAZADO: --estricto exige --manifiesto")
        return 1
    rechazos, avisos = revisar(origen, manifiesto)
    for a in avisos[:20]:
        print("aviso:", a)
    if len(avisos) > 20:
        print(f"aviso: ... y {len(avisos) - 20} más")
    for r in rechazos:
        print("RECHAZO:", r)
    print(f"{len(rechazos)} rechazos, {len(avisos)} avisos")
    return 1 if rechazos else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
